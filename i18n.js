function isSupportedLanguage(code) {
  return LANGUAGES.some((language) => language.code === code);
}

function matchBrowserLanguage(tag) {
  const lowered = tag.toLowerCase();
  const [primary] = lowered.split("-");
  if (primary === "zh") {
    if (/-(hant|tw|hk|mo)(-|$)/.test(lowered)) return "zh-Hant";
    return "zh-Hans";
  }
  return LANGUAGES.find((language) => language.code === primary)?.code ?? null;
}

function detectLanguage() {
  const requested = new URLSearchParams(window.location.search).get("lang");
  if (isSupportedLanguage(requested)) return requested;
  for (const tag of navigator.languages ?? [navigator.language]) {
    const matched = tag ? matchBrowserLanguage(tag) : null;
    if (matched) return matched;
  }
  return DEFAULT_LANGUAGE;
}

function translate(language, key, replacements = {}) {
  const template = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS[DEFAULT_LANGUAGE][key];
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => replacements[name] ?? placeholder);
}
